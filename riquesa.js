let riquesaPendents = [];
let riquesaAnterior = null;

function barrejarRiquesa() {
  riquesaPendents = [...riquesaEntrades];
  for (let i = riquesaPendents.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [riquesaPendents[i], riquesaPendents[j]] = [riquesaPendents[j], riquesaPendents[i]];
  }
  if (riquesaPendents.length > 1 && riquesaPendents[riquesaPendents.length - 1] === riquesaAnterior) {
    [riquesaPendents[0], riquesaPendents[riquesaPendents.length - 1]] =
      [riquesaPendents[riquesaPendents.length - 1], riquesaPendents[0]];
  }
}

function mostrarRiquesa() {
  if (!riquesaEntrades.length) return;
  if (!riquesaPendents.length) barrejarRiquesa();
  const entrada = riquesaPendents.pop();
  riquesaAnterior = entrada;
  document.getElementById('riquesa-category').textContent = entrada.categoria;
  document.getElementById('riquesa-expression').textContent = entrada.expressio;
  document.getElementById('riquesa-meaning').textContent = entrada.significat;
  document.getElementById('riquesa-example').textContent = entrada.exemple;
}

const botoRiquesa = document.getElementById('riquesa-next');
if (botoRiquesa) {
  botoRiquesa.addEventListener('click', mostrarRiquesa);
  mostrarRiquesa();
}
